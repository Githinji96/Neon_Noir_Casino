/**
 * Near-Miss Detector — outcome-based only.
 *
 * Reads the ACTUAL reel result. Never fabricates or manipulates outcomes.
 *
 * A near-jackpot is when 3 or 4 out of 5 jackpot symbols land on a payline,
 * but NOT all 5 (that would be an actual jackpot win).
 *
 * Per-game configuration controls which symbols count and what threshold triggers.
 *
 * FAIRNESS GUARANTEE: This function is read-only. It has no side effects on
 * RNG, payouts, balance, or jackpot probability.
 */

